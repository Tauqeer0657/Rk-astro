/**
 * Generates public/_redirects for Netlify from the actual content collection.
 *
 * Why this exists: nginx.conf does the legacy -> clean URL mapping with regex
 * (it strips the trailing WordPress post id with `(?<post>.+?)-\d+`).
 * Netlify's redirect engine has NO regex support — only `:placeholder`
 * segments and `*` splats — so every blog post needs an explicit line.
 * Generating them from the markdown frontmatter means the list cannot drift
 * out of sync when a post is added, renamed or removed.
 *
 * Run: node scripts/gen-netlify-redirects.mjs   (wired into `npm run build`)
 *
 * NEVER add a rule whose source is the target plus a trailing slash
 * ("/about-us/  /about-us"). Netlify ignores trailing slashes when matching,
 * so that rule matches /about-us itself and 301s the page to itself forever.
 * Netlify handles trailing slashes on its own.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const blogDir = join(root, 'src/content/blog');

const posts = readdirSync(blogDir)
  .filter((f) => f.endsWith('.md'))
  .map((f) => {
    const src = readFileSync(join(blogDir, f), 'utf8');
    const legacy = src.match(/^legacyPath:\s*"([^"]+)"/m)?.[1];
    const slug = f.replace(/\.md$/, '').replace(/-\d+$/, '');
    return { legacy, slug, file: f };
  });

const missing = posts.filter((p) => !p.legacy);
if (missing.length) {
  console.error('legacyPath missing in:', missing.map((m) => m.file).join(', '));
  process.exit(1);
}

// the flat pages, taken from the routes Astro actually builds
const PAGES = [
  'about-us', 'services', 'blog', 'gallery', 'contact-us',
  'advanced-prostate-care', 'kidney-stone-treatment',
  'urological-cancer-care', 'additional-urology-expertise',
];

const L = [];
L.push('# GENERATED by scripts/gen-netlify-redirects.mjs — do not edit by hand.');
L.push('# Mirrors the 301 map in nginx.conf. Netlify has no regex in _redirects,');
L.push('# so each legacy URL is written out explicitly. First match wins.');
L.push('');

L.push('# --- blog posts: /blogs/<slug>-<wordpress-id>.html -> /blog/<slug> ---');
for (const p of posts) {
  const noExt = p.legacy.replace(/\.html$/, '');
  L.push(`${p.legacy}      /blog/${p.slug}   301!`);
  L.push(`${noExt}         /blog/${p.slug}   301!`);
}
L.push('');

L.push('# --- any other /blogs/... shape falls back to the blog index ---');
L.push('/blogs/*          /blog                301!');
L.push('/blogs            /blog                301!');
L.push('');

L.push('# --- flat pages: /about-us.html -> /about-us ---');
for (const s of PAGES) {
  L.push(`/${s}.html        /${s}               301!`);
}
L.push('');

L.push('# --- homepage variants ---');
L.push('/index.html       /                    301!');
L.push('');

writeFileSync(join(root, 'public/_redirects'), L.join('\n') + '\n');
console.log(`public/_redirects written — ${posts.length} posts, ${PAGES.length} pages`);
